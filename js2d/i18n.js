  const ORDERED_PHRASES_EN = Object.entries({ ...EXTRA_PHRASES_EN, ...PHRASES_EN })
    .sort((a, b) => b[0].length - a[0].length);

  function renderTemplate(value, vars = {}) {
    if (typeof value === "function") return value(vars);
    if (typeof value !== "string") return "";
    return value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? "");
  }

  function normalizeLang(lang) {
    return lang === "en" ? "en" : "fr";
  }

  function t(lang, key, vars = {}) {
    const cleanLang = normalizeLang(lang);
    const source = STRINGS[cleanLang] || STRINGS.fr;
    const value = key.split(".").reduce((current, part) => current?.[part], source);
    const fallback = key.split(".").reduce((current, part) => current?.[part], STRINGS.fr);
    return renderTemplate(value ?? fallback ?? key, vars);
  }

  function resource(lang, key, count = 1) {
    const cleanLang = normalizeLang(lang);
    const labels = STRINGS[cleanLang]?.resource?.[key] || STRINGS.fr.resource[key] || [key, key];
    return labels[Math.abs(Number(count)) > 1 ? 1 : 0];
  }

  function entity(lang, collection, id, field, fallback = "") {
    const cleanLang = normalizeLang(lang);
    const entry = ENTITIES[cleanLang]?.[collection]?.[id];
    if (typeof entry === "string") return entry;
    return entry?.[field] || fallback;
  }

  function escapeRegExp(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function replaceLooseTerm(text, from, to) {
    const wordChars = "A-Za-z0-9_À-ÖØ-öø-ÿ";
    if (from === "l'") {
      return text.replace(new RegExp(`(^|[^${wordChars}])l'`, "g"), (_, prefix) => `${prefix}${to}`);
    }
    if (/^[A-Za-zÀ-ÖØ-öø-ÿ']+\s$/.test(from)) {
      const term = from.trim();
      return text.replace(new RegExp(`(^|[^${wordChars}])${escapeRegExp(term)}\\s+`, "g"), (_, prefix) => `${prefix}${to}`);
    }
    if (/^[A-Za-zÀ-ÖØ-öø-ÿ']+$/.test(from)) {
      return text.replace(new RegExp(`(^|[^${wordChars}])${escapeRegExp(from)}(?=$|[^${wordChars}])`, "g"), (_, prefix) => `${prefix}${to}`);
    }
    return text.split(from).join(to);
  }

  function translateChallengeText(value, lang) {
    if (normalizeLang(lang) === "fr" || typeof value !== "string") return value;
    let next = value;
    ORDERED_PHRASES_EN.forEach(([from, to]) => {
      next = replaceLooseTerm(next, from, to);
    });
    next = next
      .replace(/\s+([?.!,])/g, "$1")
      .replace(/\s{2,}/g, " ")
      .trim();
    return next;
  }

  function localizeChoice(choice, lang) {
    if (!choice || typeof choice !== "object") return choice;
    return {
      ...choice,
      label: translateChallengeText(choice.label, lang),
      feedback: translateChallengeText(choice.feedback, lang)
    };
  }

  function localizeChallenge(challenge, lang) {
    const cleanLang = normalizeLang(lang);
    if (cleanLang === "fr" || !challenge) return challenge;
    return {
      ...challenge,
      themeLabel: CHALLENGE_THEME_LABELS_EN[challenge.theme] || translateChallengeText(challenge.themeLabel, cleanLang),
      typeLabel: CHALLENGE_TYPE_LABELS_EN[challenge.type] || translateChallengeText(challenge.typeLabel, cleanLang),
      title: translateChallengeText(challenge.title, cleanLang),
      prompt: translateChallengeText(challenge.prompt, cleanLang),
      coursePoint: translateChallengeText(challenge.coursePoint, cleanLang),
      item: translateChallengeText(challenge.item, cleanLang),
      steps: Array.isArray(challenge.steps) ? challenge.steps.map((step) => translateChallengeText(step, cleanLang)) : challenge.steps,
      pool: Array.isArray(challenge.pool) ? challenge.pool.map((step) => ({ ...step, label: translateChallengeText(step.label, cleanLang) })) : challenge.pool,
      choices: Array.isArray(challenge.choices) ? challenge.choices.map((choice) => localizeChoice(choice, cleanLang)) : challenge.choices,
      categories: Array.isArray(challenge.categories) ? challenge.categories.map((choice) => localizeChoice(choice, cleanLang)) : challenge.categories
    };
  }

